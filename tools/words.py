#!/usr/bin/env python3
"""Packs data/answers.txt (the words a random game picks from) and data/allowed.txt (other words
accepted as guesses) into C: each word as 25 bits, five letters a=0..z=25, the first letter
highest, so numeric order is alphabetical; both arrays sorted for binary search.
Usage: words.py DATA_DIR OUT.c"""
import sys
d, out = sys.argv[1:3]
def load(n):
    ws = [w.strip() for w in open(f'{d}/{n}') if w.strip()]
    assert all(len(w) == 5 and w.isascii() and w.isalpha() and w.islower() for w in ws), n
    return sorted(set(ws))
def pack(w):
    v = 0
    for c in w: v = v * 32 + (ord(c) - 97)
    return v
ans, allowed = load('answers.txt'), load('allowed.txt')
allowed = [w for w in allowed if w not in set(ans)]
o = ['/* Generated by tools/words.py from data/: do not edit. */\n#include "wd.h"\n']
for name, ws in (('answers', ans), ('allowed', allowed)):
    o.append(f'static const uint32_t {name}_w[{len(ws)}] = {{\n')
    for i in range(0, len(ws), 8):
        o.append('    ' + ', '.join(f'0x{pack(w):07x}' for w in ws[i:i + 8]) + ',\n')
    o.append('};\n')
    o.append(f'const uint32_t *const {name}_words = {name}_w;\nconst int {name}_count = {len(ws)};\n')
open(out, 'w').write(''.join(o))
print(f'words: {len(ans)} answers, {len(allowed)} more guesses')
