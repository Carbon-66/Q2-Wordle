#!/usr/bin/env python3
"""Bakes the game's fonts into C: each glyph of printable ASCII as an 8-bit coverage bitmap, at the
sizes the screens use. Usage: font.py OUT.c

Fonts (both under open licences, see README.md): Clear Sans (Intel, Apache 2.0) for tiles, keys and
text, as the original game uses it; Bitter (OFL) bold for the title, a slab serif in the spirit
of the original's condensed slab logo. Paths come from $CLEAR_SANS_DIR and $BITTER_TTF, or the
defaults below."""
import os, sys
from PIL import Image, ImageDraw, ImageFont

CLEAR = os.environ.get('CLEAR_SANS_DIR', '/home/claude/dl/clear-sans/TTF')
BITTER = os.environ.get('BITTER_TTF', '/usr/share/fonts/truetype/google-fonts/ofl/bitter/Bitter[wght].ttf')

# name, file, size px, variable weight or None
FONTS = [
    ('F_TILE', f'{CLEAR}/ClearSans-Bold.ttf', 18, None),
    ('F_KEY', f'{CLEAR}/ClearSans-Bold.ttf', 18, None),
    ('F_SMALL', f'{CLEAR}/ClearSans-Bold.ttf', 11, None),
    ('F_TEXT', f'{CLEAR}/ClearSans-Regular.ttf', 13, None),
    ('F_BOLD', f'{CLEAR}/ClearSans-Bold.ttf', 13, None),
    ('F_BIG', f'{CLEAR}/ClearSans-Bold.ttf', 16, None),
    ('F_NUM', f'{CLEAR}/ClearSans-Regular.ttf', 24, None),
    ('F_HEAD', BITTER, 20, 700),
    ('F_LOGO', BITTER, 40, 800),
    ('F_HELP', f'{CLEAR}/ClearSans-Regular.ttf', 16, None),
    ('F_HELPB', f'{CLEAR}/ClearSans-Bold.ttf', 17, None),
]

out = []
out.append('/* Generated by tools/font.py: do not edit. */\n#include "wd.h"\n')
data = bytearray()
for name, path, size, weight in FONTS:
    f = ImageFont.truetype(path, size)
    if weight:
        f.set_variation_by_axes([weight])
    ascent, descent = f.getmetrics()
    glyphs = []
    for code in range(32, 127):
        ch = chr(code)
        adv = int(round(f.getlength(ch)))
        box = f.getbbox(ch, anchor='ls')  # relative to the left end of the baseline
        x0, y0, x1, y1 = box
        w, h = max(0, x1 - x0), max(0, y1 - y0)
        if ch == ' ' or w == 0 or h == 0:
            glyphs.append((0, 0, 0, 0, adv, len(data)))
            continue
        im = Image.new('L', (w + 4, h + 4), 0)
        ImageDraw.Draw(im).text((2 - x0, 2 - y0), ch, font=f, fill=255, anchor='ls')
        bb = im.getbbox()
        if not bb:
            glyphs.append((0, 0, 0, 0, adv, len(data)))
            continue
        im = im.crop(bb)
        gx, gy = bb[0] - 2 + x0, bb[1] - 2 + y0
        glyphs.append((im.width, im.height, gx, gy, adv, len(data)))
        data += im.tobytes()
    cap = -f.getbbox('H', anchor='ls')[1]
    out.append(f'static const Glyph {name.lower()}_g[95] = {{\n')
    for g in glyphs:
        out.append('    {%d, %d, %d, %d, %d, %d},\n' % g)
    out.append('};\n')
    out.append(f'static const Font {name.lower()}_f = {{ {ascent}, {descent}, {cap}, {name.lower()}_g }};\n')
out.append('static const unsigned char font_bits[%d] = {\n' % len(data))
for i in range(0, len(data), 24):
    out.append('    ' + ','.join(str(b) for b in data[i:i + 24]) + ',\n')
out.append('};\n')
out.append('const unsigned char *const font_data = font_bits;\n')
out.append('const Font *const fonts[] = { ' + ', '.join(f'&{n.lower()}_f' for n, *_ in FONTS) + ' };\n')
open(sys.argv[1], 'w').write(''.join(out))
print(f'fonts: {len(FONTS)}, {len(data)} bytes of coverage')
